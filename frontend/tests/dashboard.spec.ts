import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('Mock 示例：六角色、计划、变更、报告和刷新恢复', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: '运行 Mock 示例 →', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已完成验收')
  await expect(page.locator('.role-card')).toHaveCount(6)
  await expect(page.locator('.metric-grid').first()).toContainText('¥450.00')
  await page.getByRole('button', { name: /查看全部 .* 条/ }).click()
  await expect(page.locator('.events-list')).toContainText('#001')
  const eventIds = await page.locator('.events-list code').allTextContents()
  expect(new Set(eventIds).size).toBe(eventIds.length)
  await page.getByRole('button', { name: '仅看最近事件' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('overview-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: /范围与计划/ }).click()
  await expect(page.locator('.gantt-table tbody tr')).toHaveCount(5)
  await expect(page.locator('.gantt-table')).toContainText('Overdue reminders')
  const xmlDownloadEvent = page.waitForEvent('download')
  await page.getByRole('link', { name: '导出 Microsoft Project XML ↓' }).click()
  const xmlDownload = await xmlDownloadEvent
  expect(xmlDownload.suggestedFilename()).toBe('simulation-plan-v2.xml')
  const xml = await readFile((await xmlDownload.path())!, 'utf8')
  expect(await page.evaluate(text => new DOMParser().parseFromString(text, 'application/xml').getElementsByTagName('Task').length, xml)).toBe(5)
  await page.getByRole('button', { name: /协作与轨迹/ }).click()
  await expect(page.locator('.trace')).not.toHaveCount(0)
  await page.getByRole('button', { name: /变更与审批/ }).click()
  await expect(page.locator('.change-card')).toContainText('已应用')
  await expect(page.locator('.baseline-row')).toHaveCount(2)
  await page.getByRole('button', { name: /结项报告/ }).click()
  await expect(page.locator('.report-result')).toContainText('已完成最终验收')
  await expect(page.locator('.report tbody tr')).toHaveCount(5)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载 JSON 报告 ↓' }).click()
  const download = await downloadEvent
  const path = await download.path()
  const report = JSON.parse(await readFile(path!, 'utf8'))
  expect(report.accepted).toBe(true)
  expect(report.report.final_metrics.ac_cents).toBe(45000)
  const run = new URL(page.url()).searchParams.get('run')
  expect(run).toBeTruthy()
  await page.reload()
  await expect(page.getByRole('status')).toContainText('已完成验收')
  expect(new URL(page.url()).searchParams.get('run')).toBe(run)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.role-card')).toHaveCount(6)
  expect(await page.evaluate(() => document.body.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath('overview-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('Human 模式：通过四个版本绑定审批完成验收', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /新建实验/ }).click()
  await page.getByLabel('发起人模式').selectOption('human')
  await page.getByRole('button', { name: '启动模拟实验 →', exact: true }).click()
  for (const title of ['项目章程', '计划与变更', '计划与变更', '最终验收']) {
    const card = page.locator('.approval-card')
    await expect(card).toHaveCount(1)
    await expect(card.locator('h3')).toContainText(title)
    await card.getByLabel('审批意见').fill(`审阅 ${title} 后批准当前版本`)
    await card.getByRole('button', { name: '批准并继续', exact: true }).click()
    await expect(card).toHaveCount(0)
  }
  await expect(page.getByRole('status')).toContainText('已完成验收')
})

test('Human 拒绝章程：工作流停止，保留未完成状态', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /新建实验/ }).click()
  await page.getByLabel('发起人模式').selectOption('human')
  await page.getByRole('button', { name: '启动模拟实验 →', exact: true }).click()
  await expect(page.locator('.approval-card h3')).toContainText('项目章程')
  await page.getByRole('button', { name: '拒绝', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('提案被拒绝')
  await expect(page.locator('.approval-card')).toHaveCount(0)
  await expect(page.locator('.process-strip .reached')).toHaveCount(1)
})
